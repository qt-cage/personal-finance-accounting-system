import request from '../utils/request'
export const getAdminUsers = params => request.get('/admin/users', { params })
export const updateAdminUser = (id, data) => request.put(`/admin/users/${id}`, data)
export const getAdminCategories = () => request.get('/admin/default-categories')
export const addAdminCategory = data => request.post('/admin/default-categories', data)
export const updateAdminCategory = data => request.put('/admin/default-categories', data)
export const deleteAdminCategory = id => request.delete(`/admin/default-categories/${id}`)
export const getAdminDictionaries = () => request.get('/admin/dictionaries')
export const updateAdminDictionary = (id, data) => request.put(`/admin/dictionaries/${id}`, data)
export const getAdminLogs = params => request.get('/admin/logs', { params })
export const getAdminSettings = () => request.get('/admin/settings')
export const updateAdminSettings = data => request.put('/admin/settings', data)
export const getSystemSettings = () => request.get('/system/settings')
